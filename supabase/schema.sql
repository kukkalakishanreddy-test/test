-- Run this in Supabase SQL Editor to create the enquiry table.
-- Review the access policy with a developer before using this in production.
create table if not exists public.booking_enquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  pickup text not null,
  destination text not null,
  travel_date date,
  travellers integer not null default 2 check (travellers between 1 and 8),
  trip_type text not null,
  notes text,
  created_at timestamptz not null default now()
);

alter table public.booking_enquiries enable row level security;

-- This allows anonymous website visitors to insert enquiries only.
-- Do not add public SELECT, UPDATE, or DELETE policies.
create policy "Public can submit booking enquiries"
on public.booking_enquiries
for insert
to anon
with check (
  char_length(name) between 1 and 120
  and char_length(phone) between 8 and 30
  and char_length(pickup) between 1 and 200
  and char_length(destination) between 1 and 200
  and travellers between 1 and 8
);